// Normalize for search (handles Hebrew + partial matches, case-insensitive-ish)
export function searchCuisines(query, exclude = []) {
  const q = (query || "").trim();
  if (!q) return [];
  return CUISINE_TYPES
    .filter((c) => !exclude.includes(c))
    .filter((c) => c.includes(q))
    .slice(0, 8);
}
