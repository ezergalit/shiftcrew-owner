// ⚠️ הגרסה הראשונה סימנה שורה כ«נראתה» ברגע שהוצגה — אז מקש «אחורה» העלים אותה
// לתמיד (יותם, 14.9). מעכשיו שורה ננעלת רק ב«הבנתי» או אחרי כמה צעדים קדימה —
// לכן מפתח אחסון חדש: מה שהסימון הישן «שרף» בטעות חוזר להופיע תחת הכללים הנכונים.
const KEY = "menu-app-coach-seen2";

// כמה צעדי «קדימה» מעלימים שורה שלא אושרה ב«הבנתי». חזרה אחורה ומעבר בין
// טאבים אינם קדימה — השורה תופיע שוב בביקור הבא באותו מסך.
export const FORWARD_DISMISS = 3;

// עומק לכל מסך — הציר שעליו «קדימה» נמדד. מסכי שורש = 0.
// ⚠️ סקשן בהגדרות (`settings:<key>`) נשאר בעומק 0 דרך ה-`?? 0` למטה, בכוונה: צעד
// קדימה מזקן **כל** שורה שממתינה, ולכן פתיחת שלושה סקשנים הייתה שורפת את שורת
// הבית שהמנהל מעולם לא אישר. במחיר: שורת סקשן נסגרת רק ב«הבנתי» (או בניווט בתפריט,
// שכן מזקן) — וזה בדיוק מה שרוצים מפיצ׳ר שמסבירים אותו.
const DEPTH = { home: 0, settings: 0, "menu-door": 0, "menu-group": 1, "menu-cat": 2, "menu-dish": 3, "menu-end": 3 };

// prev ⇒ next הוא צעד קדימה? `null` הוא מסך בלי שורה (עורך המנה) — כניסה אליו
// היא קדימה, יציאה ממנו חזרה.
export function isForward(prev, next) {
  if (prev === next || prev == null) return false;
  if (next == null) return true;
  return (DEPTH[next] ?? 0) > (DEPTH[prev] ?? 0);
}

// ⚠️ אוצר המילים של השורות, נגזר מהנתונים ולא מרשימה פר-מסעדה (יותם, 14.9:
// «כתוב הקש על מנה וזה בפועל לא מנה… מסבירים לי על אזהרה כאשר אין אזהרה»).
export const hasWarning = (c) =>
  !!c && ((c.allergens?.length || 0) + (c.pregnancy?.length || 0) + (c.pitfalls?.length || 0)) > 0;

// יחיד, רבים, ומשפט ההקשה במין הנכון. `tap` של אירועים לא נוקב בשם הפריט:
// «מסלול», «תוספת» ו«קורס» חיים באותה קטגוריה ואין מילה אחת שנכונה לכולם.
// ⚠️ `fem` הוא מה שמאפשר לכל שאר המסך להתאים את עצמו: «מנה אחת» מול «נושא אחד»,
// «הבאה» מול «הבא», «עליהן» מול «עליהם». בלעדיו כל תיקון מילה היה נשאר חצי —
// «6 נושאים… לעבור עליהן שוב» (יותם, 14.9: «פשוט להתאים»).
// 🔴 צד הניהול לא מדבר באותם שדות כמו צד המלצר: `dishFromDb` מייצר `wine` (בוליאני
// לכל משקה, כולל סיגר וקוקטייל) ו-`event`, **ואין בו `knowledge` ואין `drink`**.
// בדיקה על `c.knowledge` לבדה הייתה מחזירה «מנה» לכל כרטיס הדרכה וכל סיגר —
// גרוע מהמצב שהיה. שלושת הזיהויים מקבלים את שתי הצורות.
const isKnowledgeItem = (c) =>
  c.knowledge === true || (c.category || "").startsWith("הדרכת") || (c.name || "").startsWith("מה חשוב לדעת");
const isCigarItem = (c) => c.drink === "סיגר" || /סיגר/.test(c.category || "");
// 🔴 «15 מנות» על קטגוריית שתייה קלה — נמדד חי על סטודיו. `wine`/`drink` לא
// מזהים אותה (הם רשימת משקאות אלכוהוליים ותה/קפה אינם שם), והזיהוי הזה חי
// **רק כאן**: `wine` קובע גם את תווית הצ'יפים ואת שאלות המבחן, ואין סיבה לגעת בהם.
// אותה שיטה כמו `isDrinkCategory`: המילה הראשונה, לא substring — «בקטנה ליד האוזו»
// לימדה מה קורה כשמילה של משקה יושבת באמצע שם של קטגוריית אוכל.
const headOf = (c) => String(c.category || "").trim().split(/[\s,·|/-]+/)[0] || "";
const isSoftDrink = (c) => /^(שתייה|משקא|מיץ|לימונדה|סודה|קפה|שייק|קולה)/.test(headOf(c));
const isDrinkItem = (c) => !!c.drink || c.wine === true || isSoftDrink(c);

export function itemNoun(items) {
  const list = (items || []).filter(Boolean);
  const all = (f) => list.length > 0 && list.every(f);
  if (all(isKnowledgeItem)) return { one: "נושא", many: "נושאים", fem: false, tap: "הקשה על נושא פותחת אותו לעיון" };
  if (all((c) => c.event)) return { one: "פריט", many: "פריטים", fem: false, tap: "הקשה פותחת את כל הפרטים" };
  if (all(isCigarItem)) return { one: "סיגר", many: "סיגרים", fem: false, tap: "הקשה על סיגר פותחת אותו לעיון" };
  if (all(isDrinkItem)) return { one: "משקה", many: "משקאות", fem: false, tap: "הקשה על משקה פותחת אותו לעיון" };
  return { one: "מנה", many: "מנות", fem: true, tap: "הקשה על מנה פותחת אותה לעיון" };
}

/** «מנה אחת» · «6 נושאים» — הספירה במין של מה שבאמת ברשימה. */
export function nounCount(items, n = (items || []).length) {
  const w = itemNoun(items);
  if (n === 1) return w.fem ? `${w.one} אחת` : `${w.one} אחד`;
  return `${n} ${w.many}`;
}

/** הצורות הנטויות שהמסכים צריכים — הכל נגזר מ-`fem` ולא נכתב פעמיים. */
export function nounForms(items) {
  const w = itemNoun(items);
  return {
    ...w,
    them: w.fem ? "עליהן" : "עליהם",          // «לעבור עליהן שוב»
    next: w.fem ? `ה${w.one} הבאה` : `ה${w.one} הבא`,
    prev: w.fem ? "הקודמת" : "הקודם",
    fresh: w.fem ? `${w.one} חדשה` : `${w.one} חדש`,
  };
}

