// «הדרכות שירות» ו«שתייה קלה» אינם. כשהשם לא מתחיל ב«תפריט» עוברים לניסוח
// שלא נוקב במין.
// 🔴 «הדרכות שירות» אינו `menu_group` אלא סנטינל (`"\u0000service"` ב-OwnerMenu),
// והוא הגיע לשורה כמו שהוא: ה-NUL בלתי נראה, והמנהל קרא «service — כל הקטגוריות
// שבפנים». המסך עצמו כבר ממפה אותו לכותרת שלו; השורה חייבת למפות גם.
const groupName = (name) => (String(name || "").includes("service") && String(name || "").charCodeAt(0) === 0
  ? "הדרכות שירות" : name);
const insideOf = (raw) => {
  const name = groupName(raw);
  return /^תפריט/.test(name || "") ? `${name} וכל הקטגוריות בתוכו.` : `${name} — כל הקטגוריות שבפנים.`;
};

